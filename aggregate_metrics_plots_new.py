from scipy.stats import spearmanr

def spearman_report(ycol):
    sub = summary.dropna(subset=[ycol])
    rho_all, p_all = spearmanr(sub["log_params"], sub[ycol])
    print(f"\n{ycol}: overall Spearman rho={rho_all:.3f}, p={p_all:.3g}, N={len(sub)}")

    for arch in ["transformer", "conformer"]:
        s = sub[sub["Architecture"]==arch]
        if len(s) >= 3:
            rho, p = spearmanr(s["log_params"], s[ycol])
            print(f"  {arch:<12s} rho={rho:.3f}, p={p:.3g}, N={len(s)}")
        else:
            print(f"  {arch:<12s} N={len(s)} (skipping stats)")

