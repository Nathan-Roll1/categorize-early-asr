# --- Helpers ---
def short_name(m):
    # take last path token if HF-style; then clip
    m = m.split("/")[-1]
    return m[:24]

def pick_cols(prefixes):
    return [c for c in df.columns
            if c.endswith("_peak_layer_percent") and any(c.startswith(p) for p in prefixes)]

ACOUSTIC_PREFIX = ("f0_", "f1_", "f2_", "f3_", "f3_minus_f2_", "intensity_")
SPEAKER_PREFIX  = ("gender_", "l1_background_")
TEMPORAL_PREFIX = ("duration_",)

acoustic_cols = pick_cols(ACOUSTIC_PREFIX)
speaker_cols  = pick_cols(SPEAKER_PREFIX)
temporal_cols = pick_cols(TEMPORAL_PREFIX)

assert len(temporal_cols) > 0, "No duration_*_peak_layer_percent columns found."

# --- Per-model summary ---
rows = []
for _, r in df.iterrows():
    acoustic_mean = r[acoustic_cols].mean() if len(acoustic_cols) else np.nan
    speaker_mean  = r[speaker_cols].mean()  if len(speaker_cols)  else np.nan
    temporal_mean = r[temporal_cols].mean()

    rows.append({
        "Model": r["Model"],
        "Architecture": str(r["Architecture"]).lower(),
        "Param_Count": r["Param_Count"],
        "temporal_mean": temporal_mean,
        "speaker_mean": speaker_mean,
        "acoustic_mean": acoustic_mean,
        "delta_temporal_minus_speaker": temporal_mean - speaker_mean if pd.notna(speaker_mean) else np.nan,
        "delta_temporal_minus_acoustic": temporal_mean - acoustic_mean if pd.notna(acoustic_mean) else np.nan,
    })

summary = pd.DataFrame(rows)
summary["log_params"] = np.log(summary["Param_Count"])
summary.to_csv(os.path.join(DERIVED, "summary_hierarchy_deltas.csv"), index=False)
print("📝 Saved:", os.path.join(DERIVED, "summary_hierarchy_deltas.csv"))

# --- Plotting util ---
COLOR = {"transformer": "tab:blue", "conformer": "tab:green"}
def size_from_params(x, base=1000.0):
    m = np.nanmax(x)
    return (x / m) * base if (m is not None and np.isfinite(m) and m > 0) else np.full_like(x, 200.0)

def plot_delta_vs_params(delta_col, title, fname):
    sub = summary.dropna(subset=[delta_col, "Param_Count"]).copy()
    sizes = size_from_params(sub["Param_Count"].values, base=1100.0)
    colors = [COLOR.get(a, "gray") for a in sub["Architecture"]]

    plt.figure(figsize=(9,6))
    plt.scatter(sub["Param_Count"], sub[delta_col],
                s=sizes, c=colors, alpha=0.75, edgecolors="w", linewidth=0.6)

    # labels
    texts = []
    for _, row in sub.iterrows():
        texts.append(plt.text(row["Param_Count"], row[delta_col], short_name(row["Model"]), fontsize=7))
    if HAS_ADJUST:
        adjust_text(texts, arrowprops=dict(arrowstyle="-", color="gray", lw=0.5))

    # ref line
    plt.axhline(0, color="gray", ls="--", lw=1)

    # x log scale
    plt.xscale("log")
    plt.xlabel("Parameter Count (log scale)")
    plt.ylabel(delta_col.replace("_", " ").title())
    plt.title(title)
    # legend
    handles = [
        plt.Line2D([0],[0], marker="o", color="w", label="Transformer",
                   markerfacecolor=COLOR["transformer"], markersize=8),
        plt.Line2D([0],[0], marker="o", color="w", label="Conformer",
                   markerfacecolor=COLOR["conformer"], markersize=8),
    ]
    plt.legend(handles=handles, title="Architecture", frameon=True)
    plt.grid(True, alpha=0.3)
    out = os.path.join(PLOT_DIR, fname)
    plt.tight_layout()
    plt.savefig(out, dpi=180)
    plt.close()
    print(f"📈 Saved: {out}")

