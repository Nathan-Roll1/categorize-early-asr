    if sub.empty:
        print(f"{label}: ❌ No data")
        return

    rho, p = spearmanr(sub[col1], sub[col2])
    print(f"{label}: Spearman ρ={rho:.3f}, p={p:.3g}, N={len(sub)}")

    if rho >= 0.5 and p < 0.05:
        print("👉 Conclusion: Strong alignment → safe to group.\n")
