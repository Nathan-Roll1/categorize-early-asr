# Cell 2: Leave-one-out influence on partial Spearman (Transformer set)
import numpy as np, pandas as pd
from scipy.stats import spearmanr, linregress
import matplotlib.pyplot as plt, seaborn as sns

# use tf from previous cell; if not present, recreate model_wide as above
try:
    tf
except NameError:
    # (recreate model_wide if needed)
    ROOT = "/content/drive/MyDrive/t-SNE & Probing"
    CSV = os.path.join(ROOT, "aggregate metrics", "ALLDATA_aggregate_metrics.csv")
    df = pd.read_csv(CSV)
    def hier(f):
        if f.startswith(("f0","f1","f2","f3","f3_minus_f2","intensity")): return "acoustic"
        if f.startswith("gender"): return "gender"
        if f.startswith("l1_background") or "accent" in f: return "accent"
        if f.startswith("duration"): return "duration"
        return None
    pos_cols = [c for c in df.columns if c.endswith("_peak_layer_percent")]
    pos_long = df.melt(id_vars=["Model","Architecture","Param_Count"], value_vars=pos_cols,
                       var_name="metric", value_name="peak_pct")
    pos_long["feature"] = pos_long["metric"].str.replace("_peak_layer_percent","")
    pos_long["hier"] = pos_long["feature"].apply(hier)
    pos_long = pos_long.dropna(subset=["hier"])
    model_wide = pos_long.groupby(["Model","Architecture","Param_Count","hier"])["peak_pct"].mean().unstack().reset_index()
    tf = model_wide[model_wide["Architecture"].str.lower().str.contains("transformer", na=False)].dropna(subset=["gender","accent","Param_Count"]).reset_index(drop=True)

def partial_spearman_manual(sub, x, y, cov):
    sr = sub[[x,y,cov]].rank()
    bx = linregress(sr[cov], sr[x])
    by = linregress(sr[cov], sr[y])
    rx = sr[x] - (bx.slope * sr[cov] + bx.intercept)
    ry = sr[y] - (by.slope * sr[cov] + by.intercept)
    r, p = spearmanr(rx, ry)
    return r, p

# baseline
rho_base, p_base = partial_spearman_manual(tf, "gender", "accent", "Param_Count")
print("Baseline partial rho:", rho_base, "p:", p_base, "N:", len(tf))

# leave-one-out
rows=[]
for i in range(len(tf)):
    sub = tf.drop(index=i).reset_index(drop=True)
    rho_i, p_i = partial_spearman_manual(sub, "gender", "accent", "Param_Count")
    model_name = tf.loc[i, "Model"]
    delta = rho_i - rho_base
    rows.append({"Model": model_name, "rho_leave_one_out": rho_i, "delta_vs_full": delta})

inf_df = pd.DataFrame(rows).sort_values("delta_vs_full")
